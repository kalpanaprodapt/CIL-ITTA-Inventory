    public void setTunnelName(String tunnelName) { this.tunnelName = tunnelName; }
    public List<TunnelEndpointTunnelType> getTunnelType() { return tunnelType; }
    public void setTunnelType(List<TunnelEndpointTunnelType> tunnelType) { this.tunnelType = tunnelType; }
    public String getSourceIp() { return sourceIp; }
