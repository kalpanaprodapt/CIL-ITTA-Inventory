"""Search filter for Compliance Exception and its translation to upstream query parameters."""
from __future__ import annotations

from datetime import date, datetime
from decimal import Decimal
from uuid import UUID

from pydantic import Field

from itta_core.models import ApiModel, LifecycleStatus
from itta_api.domains.compliance.compliance_exception.schemas import *  # noqa: F401,F403


class ComplianceExceptionFilter(ApiModel):
    """Query-string filter for Compliance Exception search."""

    q: str | None = Field(None, description="Free text over code, name and description")
    status: list[LifecycleStatus] | None = None
    code: str | None = Field(None, description="Code contains")
    name: str | None = Field(None, description="Name contains")
    external_ref: str | None = Field(None, description="External Ref contains")
    rule_id: UUID | None = None
    target_ref: str | None = Field(None, description="Target Ref contains")
    approved_by: str | None = Field(None, description="Approved By contains")
    expires_on_from: date | None = None
    expires_on_to: date | None = None
    effective_to_from: date | None = None
    effective_to_to: date | None = None
    labels: str | None = Field(None, description="Labels contains")
    lifecycle_stage: list[ComplianceExceptionLifecycleStage] | None = None
    source_system: str | None = Field(None, description="Source System contains")
    region: str | None = Field(None, description="Region contains")


def to_query(flt: ComplianceExceptionFilter) -> dict[str, str]:
    """Translate a filter into the query parameters understood by the inventory service."""
    params: dict[str, str] = {}
    if flt.q and flt.q.strip():
        params["q"] = flt.q.strip()
    if flt.status:
        params["status"] = ",".join(v.value for v in flt.status)
    if flt.code:
        params["code"] = flt.code.strip()
    if flt.name:
        params["name"] = flt.name.strip()
    if flt.external_ref:
        params["externalRef"] = flt.external_ref.strip()
    if flt.rule_id is not None:
        params["ruleId"] = str(flt.rule_id)
    if flt.target_ref:
        params["targetRef"] = flt.target_ref.strip()
    if flt.approved_by:
        params["approvedBy"] = flt.approved_by.strip()
    if flt.expires_on_from is not None:
        params["expiresOnFrom"] = flt.expires_on_from.isoformat()
    if flt.expires_on_to is not None:
        params["expiresOnTo"] = flt.expires_on_to.isoformat()
    if flt.effective_to_from is not None:
        params["effectiveToFrom"] = flt.effective_to_from.isoformat()
    if flt.effective_to_to is not None:
        params["effectiveToTo"] = flt.effective_to_to.isoformat()
    if flt.labels:
        params["labels"] = flt.labels.strip()
    if flt.lifecycle_stage:
        params["lifecycleStage"] = ",".join(v.value for v in flt.lifecycle_stage)
    if flt.source_system:
        params["sourceSystem"] = flt.source_system.strip()
    if flt.region:
        params["region"] = flt.region.strip()
    return params
