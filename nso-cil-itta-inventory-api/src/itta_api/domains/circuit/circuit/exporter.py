"""Tabular export of Circuit records."""
from __future__ import annotations

import csv
import io
import json
from collections.abc import Iterable

from itta_core.csvutil import cell as _cell
from itta_api.domains.circuit.circuit.schemas import CircuitRead

COLUMNS: list[tuple[str, str]] = [
    ("code", "Code"),
    ("name", "Name"),
    ("description", "Description"),
    ("status", "Status"),
    ("external_ref", "External Ref"),
    ("circuit_id", "Circuit Id"),
    ("circuit_type", "Circuit Type"),
    ("bandwidth_mbps", "Bandwidth Mbps"),
    ("provider_id", "Provider Id"),
    ("a_site_id", "A Site Id"),
    ("z_site_id", "Z Site Id"),
    ("labels", "Labels"),
    ("lifecycle_stage", "Lifecycle Stage"),
    ("source_system", "Source System"),
    ("region", "Region"),
    ("owner", "Owner"),
]


def to_row(item: CircuitRead) -> dict[str, str]:
    return {
        "code": _cell(item.code),
        "name": _cell(item.name),
        "description": _cell(item.description),
        "status": _cell(item.status),
        "external_ref": _cell(item.external_ref),
        "circuit_id": _cell(item.circuit_id),
        "circuit_type": _cell(item.circuit_type),
        "bandwidth_mbps": _cell(item.bandwidth_mbps),
        "provider_id": _cell(item.provider_id),
        "a_site_id": _cell(item.a_site_id),
        "z_site_id": _cell(item.z_site_id),
        "labels": _cell(item.labels),
        "lifecycle_stage": _cell(item.lifecycle_stage),
        "source_system": _cell(item.source_system),
        "region": _cell(item.region),
        "owner": _cell(item.owner),
    }


def to_csv(items: Iterable[CircuitRead]) -> str:
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=[c[0] for c in COLUMNS], lineterminator="\n")
    writer.writeheader()
    for item in items:
        writer.writerow(to_row(item))
    return buf.getvalue()


def to_json_lines(items: Iterable[CircuitRead]) -> str:
    return "\n".join(json.dumps(to_row(item), sort_keys=True) for item in items)


def header_labels() -> list[str]:
    return [c[1] for c in COLUMNS]
